class KalmanTrend(Indicator):
    """2상태 칼만 — 수준(level)과 기울기(slope). q 와 R 을 온라인 추정.

    ═══════════════════════════════════════════════════════════
     파라미터 — 어느 숫자가 근거가 있고 어느 게 임의인가
    ═══════════════════════════════════════════════════════════

    ★ 본체 셋 ★

        dd_lag        h.  q̂ 를 뽑을 세 점의 거리(초).
                      ★ Δt(틱 간격)와 다른 축이다 ★ 틱 간격에서는
                      세상 몫이 0.004% 라 q 를 못 뽑는다.
                      h/h* ∈ [0.5, 2] 면 충분하다 (바닥이 평평하다).
                      ▶ 기본 3.0 은 합성 데이터의 h*(=2.88). 실데이터로
                        world_frac 을 보고 0.5 근처가 되게 맞출 것.
                      ▶ h ≥ 평균 틱간격 × 6 을 지킬 것.
                      ▶ 장중에 바꾸면 안 된다. 바꿀 때는 새 객체로.
        q_halflife    q̂ 의 반감기(초). 사건에 빨리 반응해야 하므로 짧게.
                      60초 CV 0.232 지연 70초 | 20초 CV 0.449 지연 20초
                      ★ 빠르게 하려면 여기를 줄인다. dd_lag 가 아니다 ★
        var_halflife  R̂ 의 반감기(초). 사건과 무관해야 하므로 길게.
                      수렴 후 CV: 60초 0.159 | 600초 0.025 | 1800초 0.008

    ──────────────── 근거가 있는 안전장치 ────────────────

        repeat_mode   중복 스냅샷 처리. 실측으로 필요성 확인:
                        none      → 중복 96% 에서 q̂ 2700배, nis 1965
                        estimator → 추정 정상, 깨어나는 첫 10초 RMSE 11배
                        skip      → 전 구간 정상
                      ▶ repeat_frac 을 재서 고를 것
        q_floor_ratio 1e-2.  Q=0 이면 P→0, 게인→0 으로 필터 동결.
                      하한 = ratio·9R̂/h³ = "f 가 최소 ratio 는 되게".
                      ★ ratio ≪ world_frac 이어야 한다 ★ dd_lag 를
                      1.0 이하로 내리면 이것도 같이 내릴 것
                      (h=0.5 에서 하한이 진짜 q 의 1.92배가 된다).
                      ★ 측정값에서 만든다 — q̂ 자신 기준이면 래칫 ★
        r_floor_ratio 1e-3.  하한 = A_h^slow·ratio.
                      이론상 R ≤ A_h 이므로 측정값 기준 하한이다.
        min_n         30.  창키우기가 이만큼 표본을 모을 때까지 대기.

    ──────────── ★ 제가 임의로 정한 값 ★ ────────────
     근거 없음. 실데이터로 확인하거나 바꿀 것.

        lag_tol_lo    0.5   삼중항 간격 허용 하한 (h 의 배수)
        lag_tol_hi    2.0   같은 상한
        nis_halflife  30.0  nis 평균 반감기(초)
        min_dt        1e-4  Δt 하한. recv_at 이 있으므로 작게
    """

    def __init__(self,
                 # ── 입력 ──
                 source: Optional[Indicator] = None,
                 line: str = "value",
                 src: Optional[str] = None,
                 lead_s: float = 0.0,
                 # ── 본체 셋 ──
                 dd_lag: float = 3.0,
                 q_halflife: float = 60.0,
                 var_halflife: float = 1800.0,
                 # ── 고정 override (대조군 실험용) ──
                 q_fixed: Optional[float] = None,
                 obs_var: Optional[float] = None,
                 # ── 근거 있는 안전장치 ──
                 repeat_mode: str = "skip",
                 q_floor_ratio: float = 1e-2,
                 r_floor_ratio: float = 1e-3,
                 min_n: int = 30,
                 # ── 임의로 정한 값 ──
                 lag_tol_lo: float = 0.5,
                 lag_tol_hi: float = 2.0,
                 nis_halflife: float = 30.0,
                 min_dt: float = 1e-4):
        if source is None and src is None:
            raise ValueError("source 또는 src 중 하나는 있어야 한다")
        if repeat_mode not in ("skip", "estimator", "none"):
            raise ValueError("repeat_mode 는 skip/estimator/none")

        self.source = source
        self.line_name = line
        self.src = src
        self.lead_s = lead_s

        self.h = dd_lag
        self.q_halflife = q_halflife
        self.var_halflife = var_halflife

        self.q_fixed = q_fixed
        self.fixed_obs_var = obs_var

        self.repeat_mode = repeat_mode
        self.q_floor_ratio = q_floor_ratio
        self.r_floor_ratio = r_floor_ratio
        self.min_n = min_n

        self.lag_tol_lo = lag_tol_lo
        self.lag_tol_hi = lag_tol_hi
        self.nis_halflife = nis_halflife
        self.min_dt = min_dt

        # ── 반감기 → 시간상수 ──
        ln2 = math.log(2.0)
        self._q_tau = q_halflife / ln2
        self._var_tau = var_halflife / ln2
        self._nis_tau = nis_halflife / ln2

        # ── 두 lag ──
        mk = lambda hh: _Lag(hh, self._q_tau, self._var_tau,   # noqa: E731
                             lag_tol_lo, lag_tol_hi, min_dt)
        self._L1 = mk(dd_lag)          # lag h
        self._L2 = mk(2.0 * dd_lag)    # lag 2h

        # ── 추정치 ──
        self._q: Optional[float] = None
        self._R: Optional[float] = obs_var
        self._world_frac: Optional[float] = None

        # ── 중복 스냅샷 ──
        self._last_z: Optional[float] = None
        self._n_repeat = 0
        self._n_total = 0

        # ── 필터 상태 ──
        self._level: Optional[float] = None
        self._slope = 0.0
        self._p00 = 0.0
        self._p01 = 0.0
        self._p11 = 0.0
        self._prev_t: Optional[float] = None

        # ── 진단 ──
        self._V: Optional[float] = None
        self._nis_avg: Optional[float] = None
        self._n_nis = 0
        self._surprise: Optional[float] = None
        self._nis_raw: Optional[float] = None

    @property
    def warmup(self) -> Optional[int]:
        # 창키우기가 워밍업을 흡수한다. 별도 표본 수 요구가 없다.
        return None

    # ───────────────────────────────────────────────────────────
    # ① 추정 — 두 lag × 두 반감기
    # ───────────────────────────────────────────────────────────
    def _estimate(self, t: float, z: float) -> None:
        """q̂ 는 fast 쌍의 차이, R̂ 는 slow 쌍의 되대입.

            A_h  = R + q·h³/9          A_2h = R + 8q·h³/9
            빼면 R 소거  → q̂ = 9(A_2h - A_h)/(7h³)
            되대입       → R̂ = (8A_h - A_2h)/7

        ★ q̂ 식에 R̂ 이 없다 ★ lag 하나로 하면 R̂ 이 과대추정될 때
          q̂ 가 음수가 되어 필터가 얼어붙는다 (실측 -2.13e-03).
        """
        self._L1.push(t, z)
        self._L2.push(t, z)

        if not (self._L1.ready() and self._L2.ready()):
            return
        if min(self._L1.n, self._L2.n) < self.min_n:
            return

        h3 = self.h ** 3

        # ── R̂ : slow 쌍 ──
        #   이상치를 제외하지 않으므로 이것은 '깨끗한 센서 분산'이
        #   아니라 **실제로 받는 관측의 전체 분산**이다. 칼만은 선형
        #   필터이므로 그게 맞는 R 이다 (모듈 docstring 참조).
        if self.fixed_obs_var is None:
            Ah, A2h = self._L1.A_slow, self._L2.A_slow
            R_raw = (8.0 * Ah - A2h) / 7.0
            # 하한은 측정값 A_h 기준 (이론상 R ≤ A_h).
            # R̂ 자신 기준이면 승법 래칫이 생긴다.
            self._R = max(R_raw, Ah * self.r_floor_ratio)
            self._world_frac = max(0.0, min(1.0, 1.0 - self._R / Ah))

        # ── q̂ : fast 쌍 ──
        if self.q_fixed is not None:
            self._q = self.q_fixed
        else:
            Ahf, A2hf = self._L1.A_fast, self._L2.A_fast
            q_raw = 9.0 * (A2hf - Ahf) / (7.0 * h3)
            # 하한 = "f 가 최소 q_floor_ratio 는 되게".
            # Q=0 이면 P→0, 게인→0 으로 필터가 얼어붙는다(정리 A).
            # ★ ratio ≪ world_frac 이어야 한다 ★
            q_floor = self.q_floor_ratio * 9.0 * self._R / h3
            self._q = max(q_raw, q_floor)

    def _ready(self) -> bool:
        if self._R is None or self._R <= 0.0:
            return False
        if self._q is None:
            return False
        # q_fixed=0.0 은 대조군(1상태 등가)이므로 통과시킨다.
        # ★ Q=0 이면 P→0, 게인→0 으로 필터가 얼어붙는다 ★
        #   비교용으로만 쓰고 실전에 쓰지 말 것.
        return self._q > 0.0 or self.q_fixed is not None

    # ───────────────────────────────────────────────────────────
    # ② 필터
    # ───────────────────────────────────────────────────────────
    def update(self, ev):
        z = (self.source.line(self.line_name) if self.source is not None
             else getattr(ev, self.src, None))
        if z is None:
            return self.line("level")               # 입력이 아직 없다
        z = float(z)

        # ★ 중복 스냅샷 ★
        #   호가가 안 바뀌어도 H0STASP0 은 주기적으로 온다. 그러면
        #   ofi_norm 이 직전 값과 정확히 같다. 이 틱을 쓰면 세 점 중
        #   둘이 같아져 2차 차분이 1차 차분으로 퇴화한다
        #   (z₁=z₀ → D = h₁(z₂-z₀)).
        #   실측 (제외하지 않았을 때): 중복 50% → q̂ 13.4배,
        #   중복 96% → q̂ 2700배, nis 1965.
        #   시각(_prev_t)도 갱신하지 않으므로 다음 실제 틱의 Δt 에
        #   건너뛴 시간이 누적된다 — 그동안 상태가 떠내려간 만큼
        #   불확실성이 커지는 게 맞다.
        self._n_total += 1
        is_repeat = self._last_z is not None and z == self._last_z
        if is_repeat:
            self._n_repeat += 1
            if self.repeat_mode == "skip":
                self._values["repeat_frac"] = self._n_repeat / self._n_total
                return self.line("level")
        self._last_z = z

        t = _event_time(ev)
        dt = (self.min_dt if self._prev_t is None
              else max(t - self._prev_t, self.min_dt))

        # repeat_mode="estimator" 는 추정기만 건너뛰고 필터는 먹인다
        if not (is_repeat and self.repeat_mode == "estimator"):
            self._estimate(t, z)
        self._prev_t = t

        if not self._ready():
            # 아직 척도를 모른다. 어설픈 값을 내면 워밍업 구간이
            # 신호로 오인되므로 전부 None 으로 비운다.
            self._blank()
            return None

        if self._level is None:
            # 필터 시작. 첫 관측이 시드이고 P 를 크게 잡아 초반에는
            # 관측을 거의 그대로 받는다.
            self._level, self._slope = z, 0.0
            self._p00 = self._R * 1e6
            self._p01 = 0.0
            self._p11 = self._R * 1e6
            self._emit(None, None)
            return self._level

        # ── 예측  x = F x,  P = F P Fᵀ + Q ──
        self._level += self._slope * dt

        p00 = self._p00 + 2.0 * dt * self._p01 + dt * dt * self._p11
        p01 = self._p01 + dt * self._p11
        p11 = self._p11

        # Q = q̂ · M(Δt). M 의 세 성분은 Var(a), Cov(a,b), Var(b) 다.
        #   b = Δt 동안 기울기에 쌓인 잡음 → 1번 적분 → Var = q·Δt
        #   a = 위치에 쌓인 잡음           → 2번 적분 → Var = q·Δt³/3
        #   같은 잡음에서 나왔으므로 Cov(a,b) = q·Δt²/2 ≠ 0
        #
        # ★ q̂ 에 R̂ 을 곱하지 않는다 ★ 곱하면 게인에서 R 이 약분된다.
        #   고정 R 로 정상상태 게인을 재면 (Δt=1, q=1):
        #     Q=q·R : R=1e-5 → 0.756738   R=1e-1 → 0.756738  ← R 무관
        #     Q=q   : R=1e-5 → 0.985803   R=1e-1 → 0.360592  ← 교과서
        #   센서가 100배 시끄러워져도 똑같이 믿는 필터가 된다.
        q = self._q
        p00 += q * dt ** 3 / 3.0
        p01 += q * dt ** 2 / 2.0
        p11 += q * dt

        # ── 갱신. H = [1, 0] 이라 관측이 스칼라 ──
        s = p00 + self._R
        k0 = p00 / s
        k1 = p01 / s

        v = z - self._level
        self._level += k0 * v
        self._slope += k1 * v

        self._p00 = (1.0 - k0) * p00
        self._p01 = (1.0 - k0) * p01
        self._p11 = p11 - k1 * p01

        # ── 진단 ──
        kv = 1.0 - math.exp(-dt / self._var_tau)
        self._V = (v * v if self._V is None
                   else v * v * kv + self._V * (1.0 - kv))
        self._surprise = (v * v / self._V) if self._V and self._V > 0 else None
        self._nis_raw = v * v / s

        self._emit(self._nis_raw, dt)
        return self._level

    # ───────────────────────────────────────────────────────────
    def _emit(self, nis, dt):
        """nis 는 순간값이 아니라 지수평균으로 낸다.

        순간 nis 는 자유도 1 의 카이제곱이라 중앙값이 0.455 이고 꼬리가
        두껍다. 화면에서 한 값만 보면 8.24 나 0.0008 이 예사로 뜨는데
        그걸로는 판단할 수 없다. 여기도 창키우기를 쓴다 — 표본 하나로
        시드하면 그게 반감기 내내 남는다 (실측: 12개 시드의 퍼짐이
        0.56~1.95 → 평균 시드로 바꾼 뒤 0.92~1.08).
        """
        if nis is not None:
            self._n_nis += 1
            if self._nis_avg is None:
                self._nis_avg = nis
            elif dt is not None:
                k = 1.0 - math.exp(-dt / self._nis_tau)
                k = max(1.0 / self._n_nis, k)        # ← 창 키우기
                self._nis_avg = nis * k + self._nis_avg * (1.0 - k)

        self._values["level"] = self._level
        self._values["slope"] = self._slope
        self._values["lead"] = (self._level + self._slope * self.lead_s
                                if self._level is not None else None)
        self._values["obs_var"] = self._R
        self._values["q_hat"] = self._q
        self._values["world_frac"] = self._world_frac
        self._values["nis"] = self._nis_avg
        self._values["nis_raw"] = self._nis_raw
        self._values["surprise"] = self._surprise
        # 진단 전용. 게이트로 쓰지 않는다 — 평시 ~χ²₁ 이어야 하고,
        # 꼬리가 두꺼우면 ofi_norm 계산이 깨지는 틱이 있다는 뜻이다.
        self._values["r_surprise"] = self._L1.last_surprise
        # 중복 스냅샷 비율 p₀. ★ 녹음에서 반드시 확인할 것 ★
        self._values["repeat_frac"] = (self._n_repeat / self._n_total
                                       if self._n_total else None)

    def _blank(self):
        for name in ("level", "slope", "lead", "nis", "nis_raw", "surprise"):
            self._values[name] = None
        self._values["obs_var"] = self._R
        self._values["q_hat"] = self._q
        self._values["world_frac"] = self._world_frac
        self._values["r_surprise"] = self._L1.last_surprise
        self._values["repeat_frac"] = (self._n_repeat / self._n_total
                                       if self._n_total else None)