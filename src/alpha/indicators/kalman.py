def three_point(t0, z0, t1, z1, t2, z2) -> Optional[tuple]:
    """세 점에서 수준과 기울기를 소거한 조합 D 와 그 분산의 두 계수.

        c₀ = h₂,  c₁ = -(h₁+h₂),  c₂ = h₁       (h₁=t₁-t₀, h₂=t₂-t₁)
        D  = Σcᵢzᵢ        Σcᵢ=0 (수준 소거), Σcᵢtᵢ=0 (기울기 소거)
        Var(D) = q·G + R·W        G = h₁²h₂²(h₁+h₂)/3,  W = Σcᵢ²

    기하적으로 D 는 '가운데 점이 양 끝을 잇는 직선에서 벗어난 거리'에
    -(h₁+h₂) 를 곱한 값이다. 직선 = 수준 + 기울기이므로 둘이 소거된다.

    등간격이면 c=(h,-2h,h), G=(2/3)h⁵, W=6h². 간격이 달라도 정확하다 —
    위 두 조건은 h₁, h₂ 가 얼마든 항등적으로 성립한다.

    반환: (D, W, G) 또는 None
    """
    h1 = t1 - t0
    h2 = t2 - t1
    if h1 <= 0.0 or h2 <= 0.0:
        return None
    c0, c1, c2 = h2, -(h1 + h2), h1
    D = c0 * z0 + c1 * z1 + c2 * z2
    W = c0 * c0 + c1 * c1 + c2 * c2
    G = h1 * h1 * h2 * h2 * (h1 + h2) / 3.0
    if W <= 0.0 or G <= 0.0:
        return None
    return D, W, G


