# lag 하나 = 삼중항 버퍼 + 두 반감기 EMA
# ═══════════════════════════════════════════════════════════════

class _Lag:
    """목표 lag 의 삼중항을 매 틱 하나씩 뽑고, 두 반감기로 평균한다.

    fast (q 용)  : 반감기 짧게. q 는 변해야 하므로
    slow (R 용)  : 반감기 길게. R 은 상수이므로

    ★ 두 평균의 차이는 반감기뿐이다 ★ 같은 표본이 둘 다에 들어간다.
      (전 버전은 slow 에만 이상치 게이트를 걸었는데, 게이트가 필터를
       나쁘게 만든다는 측정 때문에 제거했다. 모듈 docstring 참조)

    ■ 왜 겹치게 뽑는가
        lag 마다 하나씩만 뽑으면 h=3초에서 분당 20개뿐이다. 매 틱
        뽑으면 표본이 서로 겹쳐(상관) 유효 독립 수는 명목보다 적지만
        훨씬 많다. 실측 CV: h=2.88초, 반감기 60초에서 0.232.

    ■ 간격 편차 걸러내기
        간격이 목표에서 너무 벗어난 삼중항은 버린다. 간격이 작으면
        G 가 작아져 뺄셈의 오차 증폭이 커진다.
    """

    def __init__(self, h: float, fast_tau: float, slow_tau: float,
                 tol_lo: float, tol_hi: float,
                 min_dt: float, keep: float = 3.0):
        self.h = h
        self.fast_tau = fast_tau
        self.slow_tau = slow_tau
        self.tol_lo = tol_lo
        self.tol_hi = tol_hi
        self.min_dt = min_dt
        self._span = h * keep
        self._buf: deque = deque()            # (t, z), 오래된 것이 앞

        self.A_fast: Optional[float] = None
        self.A_slow: Optional[float] = None
        self.n = 0                            # 두 EMA 가 공유 (게이트 없음)
        self._lt: Optional[float] = None
        self.last_s: Optional[float] = None
        self.last_surprise: Optional[float] = None   # s/A_slow — 진단 전용

    # ───────────────────────────────────────────────────────────
    def _at(self, target: float) -> Optional[tuple]:
        """target 이하의 가장 최근 (t, z). 버퍼가 작아 역방향 선형 탐색."""
        for tt, zz in reversed(self._buf):
            if tt <= target:
                return tt, zz
        return None

    def _w(self, dt: float, tau: float) -> float:
        """★ 창 키우기 한 줄 ★  k = max(1/n, 1-exp(-Δt/τ))

        n 이 작을 때는 1/n 이 이겨서 '지금까지 받은 전부의 정확한
        평균' 이 된다. 이론상 가장 빠른 수렴이다. n 이 커지면 EMA 가
        이기고, 긴 반감기의 매끄러움을 얻는다.

        이게 없으면 긴 반감기를 못 쓴다 — 시드의 남은 가중치가
        2^(-t/τ) 라서 반감기 30분이면 30분 뒤에도 절반이 시드다.
        """
        k = 1.0 - math.exp(-max(dt, self.min_dt) / tau)
        return max(1.0 / max(self.n, 1), k)

    def push(self, t: float, z: float) -> None:
        """값을 넣고, 삼중항이 만들어지면 두 EMA 를 갱신한다."""
        self._buf.append((t, z))
        cutoff = t - self._span
        while self._buf and self._buf[0][0] < cutoff:
            self._buf.popleft()
        if not self._buf or (t - self._buf[0][0]) < 2.0 * self.h:
            return

        p1 = self._at(t - self.h)
        p2 = self._at(t - 2.0 * self.h)
        if p1 is None or p2 is None:
            return

        # 실제 시각을 그대로 쓴다 — 목표 h 가 아니라 찾은 점의 시각
        h1 = p1[0] - p2[0]
        h2 = t - p1[0]
        lo, hi = self.h * self.tol_lo, self.h * self.tol_hi
        if not (lo <= h1 <= hi and lo <= h2 <= hi):
            return

        tp = three_point(p2[0], p2[1], p1[0], p1[1], t, z)
        if tp is None:
            return
        D, W, _G = tp
        s = D * D / W                  # E[s] = R + q·h³/9 (등간격 환산)
        self.last_s = s

        # 진단: 갱신 **전**의 A_slow 로 재야 χ²₁ 이 된다
        self.last_surprise = (s / self.A_slow
                              if self.A_slow and self.A_slow > 0.0 else None)

        if self.A_fast is None:
            self.A_fast = s
            self.A_slow = s
            self.n = 1
            self._lt = t
            return

        self.n += 1
        dt = t - self._lt
        self._lt = t
        kf = self._w(dt, self.fast_tau)
        ks = self._w(dt, self.slow_tau)
        self.A_fast = s * kf + self.A_fast * (1.0 - kf)
        self.A_slow = s * ks + self.A_slow * (1.0 - ks)

    def ready(self) -> bool:
        return self.A_fast is not None and self.A_slow is not None


